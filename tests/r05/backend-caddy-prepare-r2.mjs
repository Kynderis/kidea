import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'../..');
const sample=path.resolve(root,'../kidea-workshop-pilot/samples/r05/backend-integration-r1');
const target=path.join(sample,'caddy-r2');
fs.mkdirSync(target,{recursive:true});
const url='https://go.dev/dl/go1.26.7.linux-amd64.tar.gz';
const expected='ffb5f8de10c62550dfddab66b36b57030721e0a44a3218e9e1181d7b59f121ca';
const data=Buffer.from(await (await fetch(url,{signal:AbortSignal.timeout(120000)})).arrayBuffer());
if(data.length!==66890901||crypto.createHash('sha256').update(data).digest('hex')!==expected)throw Error('Go archive mismatch');
fs.writeFileSync(path.join(target,'go.tar.gz'),data,{flag:'wx'});
const archive=path.join(root,'.test-output/r05/backend-plan-r1/caddy-source.tar.gz');
if(crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex')!=='a593bd7077c76102ca76d19287a5e247d4e359dd67eddbc933f865afd3c131eb')throw Error('Caddy hash');
fs.mkdirSync(path.join(target,'source'));
const extracted=spawnSync('/usr/bin/tar',['-xzf',archive,'--strip-components=1','-C',path.join(target,'source')],{encoding:'utf8'});
if(extracted.status)throw Error(extracted.stderr);
console.log(JSON.stringify({url,bytes:data.length,sha256:expected,target,source:'e2eee6a7fce366321294c9c2a79f3146891dcbdf'}));
